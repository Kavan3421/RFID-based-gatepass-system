-- ==============================================================================
-- QR GATE PASS - PostgreSQL Multi-Tenant Schema for Supabase
-- ==============================================================================

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. ORGANIZATIONS (TENANTS)
CREATE TABLE IF NOT EXISTS organizations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_code VARCHAR(20) UNIQUE NOT NULL, -- e.g. GVS1024
    name VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL CHECK (type IN ('society', 'apartment', 'villa', 'office', 'commercial', 'warehouse', 'school', 'custom')),
    destination_type VARCHAR(50) NOT NULL CHECK (destination_type IN ('flat_wing', 'house_plot', 'villa', 'department', 'shop', 'custom')),
    subscription_status VARCHAR(50) DEFAULT 'ACTIVE' CHECK (subscription_status IN ('ACTIVE', 'PENDING', 'CANCELLED', 'EXPIRED')),
    subscription_tier VARCHAR(50) DEFAULT 'STANDARD',
    max_members INT DEFAULT 500,
    max_gatekeepers INT DEFAULT 10,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. USERS (ADMIN, MEMBER, GATEKEEPER)
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    username VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(20),
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'MEMBER', 'GATEKEEPER')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_org_username UNIQUE (organization_id, username)
);

-- 4. DESTINATIONS (Flats, Wings, Departments, Units)
CREATE TABLE IF NOT EXISTS destinations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    group_label VARCHAR(50), -- Wing A, Block B, Floor 3
    unit_number VARCHAR(50) NOT NULL, -- 101, HR, Shop 12
    full_name VARCHAR(100) NOT NULL, -- A-101 or IT Dept
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_org_destination UNIQUE (organization_id, full_name)
);

-- 5. GUEST PASSES (Generated by Members)
CREATE TABLE IF NOT EXISTS guest_passes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    guest_name VARCHAR(100) NOT NULL,
    guest_phone VARCHAR(20),
    pass_code VARCHAR(64) UNIQUE NOT NULL, -- Random secure token / signed hash
    valid_from TIMESTAMPTZ NOT NULL,
    valid_until TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'USED', 'EXPIRED', 'REVOKED')),
    destination_id UUID REFERENCES destinations(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. ENTRY / EXIT & DELIVERY LOGS (Live Digital Register)
CREATE TABLE IF NOT EXISTS entry_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    entry_type VARCHAR(20) NOT NULL CHECK (entry_type IN ('GUEST', 'DELIVERY')),
    person_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    company_name VARCHAR(100), -- Delivery company e.g. Amazon, Zomato, Swiggy
    destinations JSONB NOT NULL DEFAULT '[]'::jsonb, -- e.g. ["A-203", "B-104"]
    gatekeeper_id UUID REFERENCES users(id) ON DELETE SET NULL,
    pass_id UUID REFERENCES guest_passes(id) ON DELETE SET NULL,
    entry_time TIMESTAMPTZ DEFAULT NOW(),
    exit_time TIMESTAMPTZ,
    status VARCHAR(20) DEFAULT 'INSIDE' CHECK (status IN ('INSIDE', 'EXITED')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. SUBSCRIPTIONS & PAYMENTS
CREATE TABLE IF NOT EXISTS subscriptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    razorpay_order_id VARCHAR(100) UNIQUE,
    razorpay_payment_id VARCHAR(100),
    razorpay_signature VARCHAR(255),
    amount_paid NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(10) DEFAULT 'INR',
    tier_name VARCHAR(50) NOT NULL,
    status VARCHAR(20) DEFAULT 'SUCCESS',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. AUDIT LOGS
CREATE TABLE IF NOT EXISTS audit_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID REFERENCES organizations(id) ON DELETE CASCADE,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    details JSONB DEFAULT '{}'::jsonb,
    ip_address VARCHAR(45),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- INDEXES FOR HIGH-PERFORMANCE MULTI-TENANT QUERYING & REPORTING
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_users_org ON users(organization_id);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(organization_id, username);
CREATE INDEX IF NOT EXISTS idx_destinations_org ON destinations(organization_id);
CREATE INDEX IF NOT EXISTS idx_passes_org ON guest_passes(organization_id);
CREATE INDEX IF NOT EXISTS idx_passes_code ON guest_passes(pass_code);
CREATE INDEX IF NOT EXISTS idx_logs_org_time ON entry_logs(organization_id, entry_time DESC);
CREATE INDEX IF NOT EXISTS idx_logs_type ON entry_logs(organization_id, entry_type);
CREATE INDEX IF NOT EXISTS idx_logs_status ON entry_logs(organization_id, status);

